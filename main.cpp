// Бібліотека та компоненти
#include <iostream>
using namespace std;

// головна функція
int main()
{
// декларація змінних
double S, V, t;
// введення змінних
cout << "Значення S = ";
cin >> S;
cout << "Значення t = ";
cin >> t;
// перевірка правильності введених даних
if (S >= 0 && t > 0)
{ // розрахунок результату
V = S / t;
// вивід результату
cout << "V = " << V << endl;
}
else
// Якщо данні з помилкою, то
{
cout << "Помилка! S >= 0, а t > 0." << endl;
}
return 0;
}
